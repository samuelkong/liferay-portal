package com.liferay.portlet.documentlibrary;

import com.liferay.portal.kernel.exception.PortalException;
public class FileEntryTypeException extends PortalException {

	public FileEntryTypeException() {
		super();
	}

	public FileEntryTypeException(String msg) {
		super(msg);
	}

	public FileEntryTypeException(String msg, Throwable cause) {
		super(msg, cause);
	}

	public FileEntryTypeException(Throwable cause) {
		super(cause);
	}

}